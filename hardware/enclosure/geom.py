"""Archet enclosure: board geometry for the OpenSCAD model.

Reads ../kicad/archet.kicad_pcb and writes board.scad:
- HOLES: the M3 holes (H1-H6) in the board frame;
- PARTS: for each part the enclosure deals with, its F.Fab box (x0, y0, x1, y1) in the board frame and its
  3D model height range (z0, z1) above the board's underside, measured on an STL export of the model alone;
- board.stl and parts.stl (all the parts below) for the interference check in check.scad.

Board frame as in hardware/gen/board.py: origin at the top-left corner, x along the 150 mm side from the host
edge, y down. z = 0 on the board's underside. Run with KiCad's Python, cwd = enclosure.
"""
import os
import struct
import subprocess
import sys
import tempfile

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, "..", "kicad", "archet.kicad_pcb")
CLI = os.path.join(os.path.dirname(sys.executable), "kicad-cli.exe")
X0, Y0 = 50.0, 50.0   # board origin on the sheet (board.py)

# Parts the enclosure cuts, rests on or clears.
REFS = ["J1", "J2", "J3", "J5", "U6", "J7", "J8", "J9", "SW4", "J10", "J11", "J12", "SW2", "SW3", "BZ1",
        "D10", "D11", "D12", "D13", "D14", "D19"]


def stl_points(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:5] == b"solid" and b"facet" in data[:400]:
        return [tuple(map(float, ln.split()[1:4])) for ln in data.decode().splitlines()
                if ln.strip().startswith("vertex")]
    n = struct.unpack("<I", data[80:84])[0]
    pts = []
    for i in range(n):
        o = 84 + 50 * i + 12
        pts += [struct.unpack("<3f", data[o + 12 * k:o + 12 * k + 12]) for k in range(3)]
    return pts


def export_stl(out, *args):
    subprocess.run([CLI, "pcb", "export", "stl", "-f", "--user-origin", f"{X0}x{Y0}mm", "-o", out, *args, PCB],
                   check=True, capture_output=True)


def fab_box(fp):
    xs, ys = [], []
    for g in fp.GraphicalItems():
        if g.GetLayer() == pcbnew.F_Fab:
            r = g.GetBoundingBox()
            xs += [r.GetLeft(), r.GetRight()]
            ys += [r.GetTop(), r.GetBottom()]
    return (pcbnew.ToMM(min(xs)) - X0, pcbnew.ToMM(min(ys)) - Y0, pcbnew.ToMM(max(xs)) - X0, pcbnew.ToMM(max(ys)) - Y0)


def main():
    board = pcbnew.LoadBoard(PCB)
    holes = []
    for fp in board.GetFootprints():
        if fp.GetReference().startswith("H") and fp.GetFPID().GetUniStringLibItemName().startswith("MountingHole"):
            p = fp.GetPosition()
            holes.append((fp.GetReference(), pcbnew.ToMM(p.x) - X0, pcbnew.ToMM(p.y) - Y0))
    holes.sort(key=lambda h: int(h[0][1:]))
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        for ref in REFS:
            out = os.path.join(tmp, ref + ".stl")
            export_stl(out, "--no-board-body", "--component-filter", ref)
            zs = [p[2] for p in stl_points(out)]
            rows.append((ref, *fab_box(board.FindFootprintByReference(ref)), min(zs), max(zs)))
    export_stl(os.path.join(HERE, "board.stl"), "--board-only")
    export_stl(os.path.join(HERE, "parts.stl"), "--no-board-body", "--component-filter", ",".join(REFS))

    with open(os.path.join(HERE, "board.scad"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by geom.py from ../kicad/archet.kicad_pcb: do not edit.\n")
        f.write("// Board frame: x from the host edge, y down, z = 0 on the board's underside.\n")
        f.write("HOLES = [\n" + ",\n".join(f'  ["{r}", {x:.2f}, {y:.2f}]' for r, x, y in holes) + "\n];\n")
        f.write("// [ref, fab x0, y0, x1, y1, model z0, z1]\n")
        f.write("PARTS = [\n" + ",\n".join(
            f'  ["{r[0]}", ' + ", ".join(f"{v:.2f}" for v in r[1:]) + "]" for r in rows) + "\n];\n")
    for r in rows:
        print(f"{r[0]:4} x {r[1]:7.2f}..{r[3]:7.2f}  y {r[2]:6.2f}..{r[4]:6.2f}  z {r[5]:6.2f}..{r[6]:6.2f}")
    print("holes", holes)


if __name__ == "__main__":
    main()
